#!/usr/bin/env python3
"""Bundle the modular sources into single-file Luau scripts.

Roblox executors load one script via loadstring(), so the module tree in
`src/` has to be flattened. This emits a tiny module registry and rewrites
`require(...)` paths to registry lookups.

Usage:
    python3 build/bundle.py            # write dist/*.lua
    python3 build/bundle.py --check    # verify dist matches sources
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

# Entry point -> output file
TARGETS = {
    "admin": ("admin/init.lua", "Admin.lua", "Admin"),
    "tester": ("tester/init.lua", "Tester.lua", "Tester"),
}

SHARED_ORDER = [
    "Config",
    "Util",
    "Log",
    "Signal",
    "Env",
    "Protocol",
    "Transport",
    "Sync",
    "Catalogue",
    "PlotService",
    "DuelService",
    "Ui",
]

HEADER = """--[[
	{app} — {role} ({version})
	Generated by build/bundle.py. Do not edit directly; edit src/ and rebuild.
	Source layout: src/shared/*.lua, src/{folder}/init.lua
]]

local __modules = {{}}
local __cache = {{}}

local function __require(name)
	local cached = __cache[name]
	if cached ~= nil then
		return cached
	end
	local factory = __modules[name]
	if not factory then
		error("unknown module: " .. tostring(name), 2)
	end
	local result = factory()
	__cache[name] = result
	return result
end
"""


def read_version() -> str:
    text = (SRC / "shared" / "Config.lua").read_text(encoding="utf-8")
    match = re.search(r'Config\.VERSION\s*=\s*"([^"]+)"', text)
    return match.group(1) if match else "0.0.0"


def rewrite_requires(body: str) -> str:
    """Turn every require(<path>.Name) form into __require("Name")."""
    patterns = [
        # require(script.Parent.Config) / require(script.Parent.Parent.shared.X)
        r'require\(\s*(?:script\.)?(?:Parent\.)*(?:shared\.)?([A-Za-z_][A-Za-z0-9_]*)\s*\)',
        # require(Shared.Config)
        r'require\(\s*Shared\.([A-Za-z_][A-Za-z0-9_]*)\s*\)',
    ]
    for pattern in patterns:
        body = re.sub(pattern, lambda m: f'__require("{m.group(1)}")', body)
    return body


def strip_shared_alias(body: str) -> str:
    """Remove the `local Shared = script...` line, meaningless once bundled."""
    return re.sub(r'^local Shared = script[^\n]*\n', '', body, flags=re.MULTILINE)


def module_chunk(name: str, path: Path) -> str:
    body = path.read_text(encoding="utf-8")
    body = strip_shared_alias(body)
    body = rewrite_requires(body)
    indented = "\n".join(
        ("\t" + line if line.strip() else line) for line in body.splitlines()
    )
    return f'__modules["{name}"] = function()\n{indented}\nend\n'


def build(entry_key: str) -> str:
    rel, _out, role = TARGETS[entry_key]
    version = read_version()

    parts = [
        HEADER.format(app="Spoofer", role=role, version=version, folder=entry_key)
    ]

    for name in SHARED_ORDER:
        path = SRC / "shared" / f"{name}.lua"
        if not path.exists():
            raise SystemExit(f"missing shared module: {path}")
        parts.append(module_chunk(name, path))

    entry_path = SRC / rel
    parts.append(module_chunk(role, entry_path))
    parts.append(f'\nreturn __require("{role}").start()\n')

    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if dist/ is stale instead of writing")
    args = parser.parse_args()

    DIST.mkdir(exist_ok=True)
    stale = []

    for key, (_rel, out, _role) in TARGETS.items():
        content = build(key)
        target = DIST / out

        if args.check:
            if not target.exists():
                stale.append(f"{out} (missing)")
                continue
            existing = target.read_text(encoding="utf-8")
            if hashlib.sha256(existing.encode()).hexdigest() != \
               hashlib.sha256(content.encode()).hexdigest():
                stale.append(f"{out} (out of date)")
        else:
            target.write_text(content, encoding="utf-8")
            lines = content.count("\n")
            print(f"wrote {target.relative_to(ROOT)} ({lines} lines, "
                  f"{len(content) / 1024:.1f} KiB)")

    if args.check:
        if stale:
            print("dist is stale: " + ", ".join(stale), file=sys.stderr)
            print("run: python3 build/bundle.py", file=sys.stderr)
            return 1
        print("dist is up to date")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
